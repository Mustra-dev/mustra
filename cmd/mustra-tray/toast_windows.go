//go:build windows

package main

import (
	"context"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"syscall"
	"time"
)

// createNoWindow is CREATE_NO_WINDOW: a console application started with it
// gets no console at all, rather than one that is hidden after the fact.
const createNoWindow = 0x08000000

// Rendering a real Windows toast.
//
// The notification itself is WinRT, which has no pure-Go binding worth
// carrying, so the XML is built here and handed to PowerShell to show. That
// is a compromise and worth naming: it costs a process launch per toast,
// perhaps 300ms, on an event that happens a few times a day. The
// alternative was cgo, which would have taken the agent's whole build --
// six cross-compiled targets from one Linux container, CGO_ENABLED=0 -- and
// turned it into a per-platform build problem for a notification.
//
// The XML is generated by encoding/xml rather than by pasting strings
// together, because every field in it is operator-written text and one
// unescaped quote in a button label would otherwise produce a toast that
// silently never appears.

// showToast hands the document to PowerShell, which shows it under this
// application's identity so the name and icon are ours rather than
// PowerShell's.
func showToast(ctx context.Context, n *notification, logoPath string) error {
	doc, err := buildToastXML(n, logoPath)
	if err != nil {
		return err
	}

	// The XML reaches PowerShell base64-encoded rather than interpolated.
	// The alternative is quoting operator-written text through a shell,
	// which is the same mistake that stopped the installer's Python check
	// working on 5.1.
	script := `
$ErrorActionPreference = 'Stop'
[Windows.UI.Notifications.ToastNotificationManager, Windows.UI.Notifications, ContentType=WindowsRuntime] | Out-Null
[Windows.Data.Xml.Dom.XmlDocument, Windows.Data.Xml.Dom.XmlDocument, ContentType=WindowsRuntime] | Out-Null
$xml = [Windows.Data.Xml.Dom.XmlDocument]::new()
$xml.LoadXml([Text.Encoding]::UTF8.GetString([Convert]::FromBase64String($env:MUSTRA_TOAST_XML)))
$toast = [Windows.UI.Notifications.ToastNotification]::new($xml)
$toast.Tag = 'mustra'
$toast.Group = 'mustra'
[Windows.UI.Notifications.ToastNotificationManager]::CreateToastNotifier($env:MUSTRA_TOAST_APPID).Show($toast)
`
	cctx, cancel := context.WithTimeout(ctx, 20*time.Second)
	defer cancel()
	cmd := exec.CommandContext(cctx, powershellPath(), "-NoProfile", "-NonInteractive", "-Command", script)
	// No console window. This helper is built -H windowsgui and has no
	// console of its own, so spawning one flashes a black box on screen for
	// the fraction of a second the toast takes to raise -- which is a
	// strange thing to show somebody every time you notify them.
	//
	// CREATE_NO_WINDOW is what actually suppresses it for a console
	// application; HideWindow alone leaves a window that is merely not
	// shown, and some builds still flash it.
	cmd.SysProcAttr = &syscall.SysProcAttr{HideWindow: true, CreationFlags: createNoWindow}
	cmd.Env = append(os.Environ(),
		"MUSTRA_TOAST_XML="+base64Std(doc),
		"MUSTRA_TOAST_APPID="+appUserModelID,
	)
	var stderr strings.Builder
	cmd.Stderr = &stderr
	if err := cmd.Run(); err != nil {
		return fmt.Errorf("%w: %s", err, strings.TrimSpace(stderr.String()))
	}
	return nil
}

func powershellPath() string {
	if root := os.Getenv("SystemRoot"); root != "" {
		return filepath.Join(root, "System32", "WindowsPowerShell", "v1.0", "powershell.exe")
	}
	return "powershell.exe"
}
