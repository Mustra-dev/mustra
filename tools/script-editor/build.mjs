import { build } from "esbuild";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(fileURLToPath(import.meta.url));
const output = resolve(root, "../../internal/server/static/vendor");
await mkdir(output, { recursive: true });
const result = await build({
  absWorkingDir: root, entryPoints: ["editor.js"], bundle: true, minify: true,
  format: "iife", target: ["es2020"], metafile: true,
  outfile: resolve(output, "script-editor.js"),
  banner: { js: "/* Generated by tools/script-editor. See script-editor.LICENSE.txt. */" },
});
const packages = [...new Set(Object.keys(result.metafile.inputs)
  .map(path => path.match(/^node_modules\/((?:@[^/]+\/)?[^/]+)/)?.[1]).filter(Boolean))].sort();
const notices = await Promise.all(packages.map(async name => {
  const base = resolve(root, "node_modules", name);
  const pkg = JSON.parse(await readFile(resolve(base, "package.json"), "utf8"));
  return `${name} ${pkg.version}\n${await readFile(resolve(base, "LICENSE"), "utf8")}`;
}));
await writeFile(resolve(output, "script-editor.LICENSE.txt"), notices.join("\n---\n\n"));
